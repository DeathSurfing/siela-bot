export interface CallPhrase {
  text: string;
  genericIndex: number | null;
}

export function buildCallPhrase(
  number: number,
  lastGenericIndex: number | null = null,
  random: () => number = Math.random,
): CallPhrase {
  const classic = BINGO_CALLS[number];
  if (classic) return { text: `Number ${number}. ${classic}.`, genericIndex: null };

  let index = Math.floor(random() * GENERIC_FLAVOURS.length);
  if (lastGenericIndex !== null && index === lastGenericIndex) {
    index = (index + 1) % GENERIC_FLAVOURS.length;
  }
  return {
    text: `Number ${number}. ${GENERIC_FLAVOURS[index]}`,
    genericIndex: index,
  };
}
