#!/usr/bin/env bash
# Siela voice fleet — generate a compose overlay with N voice worker nodes.
#
# Usage:
#   scripts/make-voice-overlay.sh 3
#
# Reads per-node tokens from deploy/podman/.env.voice-<i> (see
# .env.voice.example) and writes deploy/podman/compose.voice.generated.yaml,
# which scripts/podman-stack.sh includes automatically when present.
# Prints the NODES line to add to deploy/podman/.env for the router.
#
# Each worker is the same bot image with NODE_ROLE=voice and its own
# DISCORD_TOKEN. The commander (siela-bot) stays node "commander".

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_DIR="${ROOT_DIR}/deploy/podman"
OUT="${ENV_DIR}/compose.voice.generated.yaml"

COUNT="${1:-}"
if ! [[ "${COUNT}" =~ ^[0-9]+$ ]] || [[ "${COUNT}" -lt 1 ]] || [[ "${COUNT}" -gt 32 ]]; then
  echo "usage: $0 <count 1..32>" >&2
  exit 1
fi

for i in $(seq 1 "${COUNT}"); do
  if [[ ! -f "${ENV_DIR}/.env.voice-${i}" ]]; then
    echo "error: missing ${ENV_DIR}/.env.voice-${i} (copy .env.voice.example)" >&2
    exit 1
  fi
done

{
  echo "# Generated by scripts/make-voice-overlay.sh ${COUNT} — do not edit."
  echo "# Regenerate after changing the worker count."
  echo "services:"
  for i in $(seq 1 "${COUNT}"); do
    cat <<EOF
  bot-voice-${i}:
    image: localhost/siela-bot:latest
    container_name: siela-voice-${i}
    env_file: .env.voice-${i}
    networks:
      edge:
      data:
      control:
    depends_on:
      - postgres
      - valkey
    environment:
      NODE_ROLE: voice
      NODE_ID: voice-${i}
      DATABASE_URL: \${DATABASE_URL}
      VALKEY_URL: \${VALKEY_URL:-redis://valkey:6379}
      WORKER_INTERNAL_PORT: 3101
    restart: unless-stopped
    init: true
    read_only: true
    tmpfs:
      - /tmp
    security_opt:
      - no-new-privileges:true
    cap_drop: [ALL]
    healthcheck:
      test: ["CMD-SHELL", "python3 -c \\"import urllib.request; urllib.request.urlopen('http://127.0.0.1:3002/healthz')\\""]
      interval: 15s
      timeout: 5s
      retries: 10
    mem_limit: 4g
EOF
  done
} >"${OUT}"

NODES="commander=http://bot-control:3101"
for i in $(seq 1 "${COUNT}"); do
  NODES="${NODES},voice-${i}=http://bot-voice-${i}:3101"
done

echo "wrote ${OUT} with ${COUNT} worker(s)"
echo "add to deploy/podman/.env:"
echo "NODES=${NODES}"
echo
echo "invite each worker to the guild (same scopes/permissions as the commander):"
for i in $(seq 1 "${COUNT}"); do
  CLIENT_ID="$(grep -E '^DISCORD_CLIENT_ID=' "${ENV_DIR}/.env.voice-${i}" 2>/dev/null | tail -n 1 | cut -d= -f2- | tr -d '\r"' || true)"
  GUILD_ID="$(grep -E '^GUILD_ID=' "${ENV_DIR}/.env" 2>/dev/null | tail -n 1 | cut -d= -f2- | tr -d '\r"' || true)"
  if [[ -n "${CLIENT_ID}" ]]; then
    URL="https://discord.com/oauth2/authorize?client_id=${CLIENT_ID}&scope=bot%20applications.commands&permissions=322292816"
    if [[ -n "${GUILD_ID:-}" ]]; then
      URL="${URL}&guild_id=${GUILD_ID}&disable_guild_select=true"
    fi
    echo "voice-${i}: ${URL}"
  else
    echo "voice-${i}: set DISCORD_CLIENT_ID in .env.voice-${i} to print its invite URL"
  fi
done
