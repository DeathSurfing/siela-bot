#!/usr/bin/env bash
# Siela Bot — generate the minimal Podman .env.
#
# Required environment:
#   DISCORD_TOKEN
#
# Optional:
#   DISCORD_CLIENT_ID  (otherwise derived from the token)
#   GUILD_ID           (otherwise the bot serves every guild it joins)
#   DASHBOARD_PASSWORD (otherwise generated)
#   DASHBOARD_SESSION_SECRET (otherwise generated)
#   DASHBOARD_PORT     (host port, default 3000)
#   WATCHTOWER_ENABLED (true starts the auto-deploy watchtower; default false)
#   WATCHTOWER_REPO_URL (fork URL to follow instead of upstream)
#   WATCHTOWER_BRANCH  (default main)
#   WATCHTOWER_REPO_DIR (default: this checkout)
#   GH_TOKEN           (private forks and CI-gate API headroom)
#   FORCE=1            (overwrite an existing .env)
#
# The script generates POSTGRES_PASSWORD, MCP_TOKEN (internal control API
# bearer), WATCHTOWER_TOKEN, and dashboard credentials, then writes
# deploy/podman/.env with mode 600.

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_DIR="${ROOT_DIR}/deploy/podman"
ENV_FILE="${ENV_DIR}/.env"

if [[ -z "${DISCORD_TOKEN:-}" ]]; then
  echo "error: DISCORD_TOKEN is required" >&2
  exit 1
fi

if [[ -f "${ENV_FILE}" && "${FORCE:-0}" != "1" ]]; then
  echo "error: ${ENV_FILE} already exists; set FORCE=1 to overwrite" >&2
  exit 1
fi

rand_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 48 | tr -d '\n/+=' | cut -c1-40
  else
    tr -dc 'A-Za-z0-9' </dev/urandom | head -c 40
  fi
}

derive_client_id() {
  if [[ -n "${DISCORD_CLIENT_ID:-}" ]]; then
    printf '%s' "${DISCORD_CLIENT_ID}"
    return 0
  fi
  if ! command -v curl >/dev/null 2>&1 || ! command -v python3 >/dev/null 2>&1; then
    return 1
  fi
  local response
  response="$(curl -fsS -H "Authorization: Bot ${DISCORD_TOKEN}" \
    https://discord.com/api/v10/oauth2/applications/@me 2>/dev/null || true)"
  printf '%s' "${response}" | python3 -c 'import json,sys; print(json.load(sys.stdin)["id"])' 2>/dev/null
}

CLIENT_ID="$(derive_client_id || true)"
if [[ -z "${CLIENT_ID}" ]]; then
  echo "error: could not derive DISCORD_CLIENT_ID; set it explicitly" >&2
  exit 1
fi

POSTGRES_PASSWORD="$(rand_secret)"
MCP_TOKEN="$(rand_secret)"
WATCHTOWER_TOKEN="$(rand_secret)"
DASHBOARD_PASSWORD="${DASHBOARD_PASSWORD:-$(rand_secret)}"
DASHBOARD_SESSION_SECRET="${DASHBOARD_SESSION_SECRET:-$(rand_secret)}"
DASHBOARD_PORT="${DASHBOARD_PORT:-3000}"

WATCHTOWER_ENABLED="${WATCHTOWER_ENABLED:-false}"
WATCHTOWER_REPO_DIR="${WATCHTOWER_REPO_DIR:-${ROOT_DIR}}"
WATCHTOWER_REPO_URL="${WATCHTOWER_REPO_URL:-https://github.com/DeathSurfing/siela-bot.git}"
WATCHTOWER_BRANCH="${WATCHTOWER_BRANCH:-main}"

umask 077
cat >"${ENV_FILE}" <<EOF
# Generated by scripts/podman-init.sh — do not commit.
DISCORD_TOKEN=${DISCORD_TOKEN}
DISCORD_CLIENT_ID=${CLIENT_ID}
GUILD_ID=${GUILD_ID:-}
DASHBOARD_PASSWORD=${DASHBOARD_PASSWORD}
DASHBOARD_SESSION_SECRET=${DASHBOARD_SESSION_SECRET}
DASHBOARD_PORT=${DASHBOARD_PORT}

POSTGRES_USER=siela
POSTGRES_DB=siela
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
DATABASE_URL=postgres://siela:${POSTGRES_PASSWORD}@postgres:5432/siela
MCP_TOKEN=${MCP_TOKEN}

WATCHTOWER_ENABLED=${WATCHTOWER_ENABLED}
WATCHTOWER_REPO_URL=${WATCHTOWER_REPO_URL}
WATCHTOWER_BRANCH=${WATCHTOWER_BRANCH}
WATCHTOWER_REPO_DIR=${WATCHTOWER_REPO_DIR}
WATCHTOWER_TOKEN=${WATCHTOWER_TOKEN}
GH_TOKEN=${GH_TOKEN:-}


CONTROL_API_URL=http://bot-control:3001
DEFAULT_PREFIX=!
LOG_LEVEL=info
TZ=UTC
EOF

chmod 600 "${ENV_FILE}"

INVITE_URL="https://discord.com/oauth2/authorize?client_id=${CLIENT_ID}&scope=bot%20applications.commands&permissions=322292816"
if [[ -n "${GUILD_ID:-}" ]]; then
  INVITE_URL="${INVITE_URL}&guild_id=${GUILD_ID}&disable_guild_select=true"
fi

echo "wrote ${ENV_FILE} (mode 600)"
echo "client id: ${CLIENT_ID}"
echo "guild id: ${GUILD_ID:-auto-detect}"
echo "generated: POSTGRES_PASSWORD, MCP_TOKEN (control API bearer), WATCHTOWER_TOKEN"
echo "generated: DASHBOARD_PASSWORD, DASHBOARD_SESSION_SECRET"
echo "dashboard: http://<host>:${DASHBOARD_PORT} (password is DASHBOARD_PASSWORD in ${ENV_FILE})"
echo "WATCHTOWER: ${WATCHTOWER_ENABLED} (follows ${WATCHTOWER_REPO_URL} ${WATCHTOWER_BRANCH})"
echo "invite: ${INVITE_URL}"
echo "next: scripts/podman-stack.sh up -d --build"
